export function filterDiningMerchants(
  merchants: DiningMerchant[],
  filters: DiningFilterState,
): DiningMerchant[] {
  return merchants.filter(
    (merchant) =>
      (filters.region === "all" || merchant.region === filters.region) &&
      (filters.status === "all" || merchant.status === filters.status) &&
      (filters.category === "all" || merchant.category === filters.category),
  );
}
